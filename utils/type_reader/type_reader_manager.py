from utils.type_reader.amf3_util import _get_amf3_reader
from utils.type_reader.protobuf_util import _get_protobuf_reader


class TypeReaderManager:
    def __init__(self):
        self.readers = {
            "amf3": _get_amf3_reader(),
            "protobuf": _get_protobuf_reader()
        }

    def read_bytes(self, _bytes, method):
        reader = self.readers[method]
        return reader.read_bytes(_bytes)

    def reverse_body(self, data, method):
        reader = self.readers[method]
        return reader.reverse_body(data)


def get_type_reader_manager():
    return TypeReaderManager()


